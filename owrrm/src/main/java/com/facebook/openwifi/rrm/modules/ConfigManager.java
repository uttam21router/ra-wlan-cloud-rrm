/**
 * Device configuration manager module.
 */
public class ConfigManager implements Runnable {
	private static final Logger logger =
		LoggerFactory.getLogger(ConfigManager.class);

	/** The module parameters. */
	private final ConfigManagerParams params;

	/** The device data manager. */
	private final DeviceDataManager deviceDataManager;

	/** The uCentral client. */
	private final UCentralClient client;

	/** Monotonic clock, injectable for retry/debounce tests. */
	private final LongSupplier nanoTime;

	/** Runtime per-device data. */
	private class DeviceData {
		/** Last config time (in monotonic ns). */
		public Long lastConfigTimeNs;
		/** Do not retry failed delivery before the normal loop interval. */
		public Long configRetryAfterNs;
		/** Only capability retrieval failures are automatically retried. */
		public Long bandwidthRetryAfterNs;
		public Integer bandwidthRetryWidth;
	}

	/** Map from device serial number to runtime data. */
	private Map<String, DeviceData> deviceDataMap = new TreeMap<>();

	/** The main thread reference (i.e. where {@link #run()} is invoked). */
	private Thread mainThread;

	/** Was the main thread interrupt generated by {@link #wakeUp()}? */
	private final AtomicBoolean wakeupFlag = new AtomicBoolean(false);

	/** Is the main thread sleeping? */
	private final AtomicBoolean sleepingFlag = new AtomicBoolean(false);

	/**
	 * Thread-safe set of zones for which manual config updates have been
	 * requested.
	 */
	private Set<String> zonesToUpdate = ConcurrentHashMap.newKeySet();

	/** Config listener interface. */
	public interface ConfigListener {
		/**
		 * Receive a new device config.
		 *
		 * The listener should NOT modify the "config" parameter.
		 */
		void receiveDeviceConfig(
			String serialNumber,
			UCentralApConfiguration config
		);

		/**
		 * Process a received device config.
		 *
		 * The listener should modify the "config" parameter as necessary and
		 * return true if any changes were made, otherwise return false.
		 */
		boolean processDeviceConfig(
			String serialNumber,
			UCentralApConfiguration config
		);
	}

	/** State listeners. */
	private Map<String, ConfigListener> configListeners = new TreeMap<>();

	/** Constructor. */
	public ConfigManager(
		ConfigManagerParams params,
		DeviceDataManager deviceDataManager,
		UCentralClient client
	) {
		this(params, deviceDataManager, client, System::nanoTime);
	}

	ConfigManager(
		ConfigManagerParams params,
		DeviceDataManager deviceDataManager,
		UCentralClient client,
		LongSupplier nanoTime
	) {
		this.params = params;
		this.deviceDataManager = deviceDataManager;
		this.client = client;
		this.nanoTime = nanoTime;

		// Apply RRM parameters
		addConfigListener(
			getClass().getSimpleName(),
			new ConfigListener() {
				@Override
				public void receiveDeviceConfig(
					String serialNumber,
					UCentralApConfiguration config
				) {
					// do nothing
				}

				@Override
				public boolean processDeviceConfig(
					String serialNumber,
					UCentralApConfiguration config
				) {
					return applyRRMConfig(serialNumber, config);
				}
			}
		);
	}

	@Override
	public void run() {
		this.mainThread = Thread.currentThread();

		// Run application logic in a periodic loop
		while (!Thread.currentThread().isInterrupted()) {
			try {
				runImpl();
				sleepingFlag.set(true);
				Thread.sleep(params.updateIntervalMs);
				wakeupFlag.set(false);
			} catch (InterruptedException e) {
				if (wakeupFlag.getAndSet(false)) {
					// Intentional interrupt, clear flag
					logger.debug("Interrupted by wakeup!");
					Thread.interrupted();
					continue;
				} else {
					logger.error("Interrupted!", e);
					break;
				}
			} finally {
				sleepingFlag.set(false);
			}
		}
		logger.error("Thread terminated!");
	}

	/** Run single iteration of application logic. */
	void runImpl() {
		while (!client.isInitialized()) {
			logger.trace("Waiting for ucentral client");
			try {
				Thread.sleep(2000);
			} catch (InterruptedException e) {
				Thread.currentThread().interrupt();
				return;
			}
		}

		// Fetch device list
		List<DeviceWithStatus> devices = client.getDevices();
		if (devices == null) {
			logger.error("Failed to fetch devices!");
			return;
		}
		logger.debug("Received device list of size = {}", devices.size());

		long now = nanoTime.getAsLong();

		// Apply any config updates locally
		Map<String, String> devicesNeedingUpdate = new HashMap<>();
		final long CONFIG_DEBOUNCE_INTERVAL_NS =
			params.configDebounceIntervalSec * 1_000_000_000L;
		Set<String> zonesToUpdateCopy = new HashSet<>(zonesToUpdate);
		// use removeAll() instead of clear() in case items are added between
		// the previous line and the following line
		zonesToUpdate.removeAll(zonesToUpdateCopy);
		for (DeviceWithStatus device : devices) {
			// Update config structure
			DeviceData data = deviceDataMap.computeIfAbsent(
				device.serialNumber,
				k -> new DeviceData()
			);
			// Update the device only when it is still connected
			if (!device.connected) {
				String zone =
					deviceDataManager.getDeviceZone(device.serialNumber);
				if (zone != null && zonesToUpdateCopy.contains(zone)) {
					zonesToUpdate.add(zone);
				}
				logger.info(
					"Device {} is disconnected, skipping...",
					device.serialNumber
				);
				continue;
			}
			UCentralApConfiguration config =
				new UCentralApConfiguration(device.configuration);

			// Call receive listeners
			for (ConfigListener listener : configListeners.values()) {
				listener.receiveDeviceConfig(device.serialNumber, config);
			}
			// Check if there are requested updates for this zone
			String deviceZone =
				deviceDataManager.getDeviceZone(device.serialNumber);
			boolean isEvent = zonesToUpdateCopy.contains(deviceZone);
			if (params.configOnEventOnly && !isEvent) {
				logger.debug(
					"Skipping config for {} (zone not marked for updates)",
					device.serialNumber
				);
				continue;
			}

			// Check if pushing config is enabled in device config
			if (!isDeviceConfigEnabled(device.serialNumber)) {
				logger.debug(
					"Skipping config for {} (disabled in device config)",
					device.serialNumber
				);
				continue;
			}

			// Call processing listeners
			boolean modified = false;
			for (ConfigListener listener : configListeners.values()) {
				boolean wasModified = listener.processDeviceConfig(
					device.serialNumber,
					config
				);
				if (wasModified) {
					modified = true;
				}
			}

			// Queue config update if past debounce interval
			if (modified) {
				if (
					data.configRetryAfterNs != null &&
						now - data.configRetryAfterNs < 0
				) {
					retainZoneForRetry(device.serialNumber);
					continue;
				}
				if (
					data.lastConfigTimeNs != null &&
						now - data.lastConfigTimeNs <
							CONFIG_DEBOUNCE_INTERVAL_NS
				) {
					logger.debug(
						"Skipping config for {} (last configured {}s ago)",
						device.serialNumber,
						(now - data.lastConfigTimeNs) / 1_000_000_000L
					);
					if (isEvent) {
						zonesToUpdate.add(deviceZone);
					}
					continue;
				} else {
					devicesNeedingUpdate
						.put(device.serialNumber, config.toString());
				}
			}
		}

		final boolean shouldUpdate = !zonesToUpdateCopy.isEmpty();
		// Send config changes to devices
		if (!params.configEnabled) {
			logger.trace("Config changes are disabled.");
		} else if (devicesNeedingUpdate.isEmpty()) {
			logger.debug("No device configs to send.");
		} else if (params.configOnEventOnly && !shouldUpdate) {
			// shouldn't happen
			logger.error(
				"ERROR!! {} device(s) queued for config update, but no zones queued for update.",
				devicesNeedingUpdate.size()
			);
		} else {
			// TODO: Replace with the newer owprov API to send only deltas, not
			// the full configuration blobs:
			//   PUT /configurationOverrides/{serialNumber}?source=owrrm
			logger.info(
				"Sending config to {} device(s): {}",
				devicesNeedingUpdate.size(),
				String.join(", ", devicesNeedingUpdate.keySet())
			);
			for (
				Map.Entry<String, String> entry : devicesNeedingUpdate
					.entrySet()
			) {
				String serialNumber = entry.getKey();
				DeviceData data = deviceDataMap.get(serialNumber);
				logger.info(
					"Device {}: sending new configuration...",
					serialNumber
				);
				try {
					CommandInfo result =
						client.configure(serialNumber, entry.getValue());
					// Keep configuration delivery independent of the scan API's
					// stricter acknowledgment contract. Gateway versions may omit
					// command identity, status, UUID or timing metadata.
					if (result != null && result.errorCode == 0) {
						data.lastConfigTimeNs = nanoTime.getAsLong();
						data.configRetryAfterNs = null;
					} else {
						logger.error(
							"Device {}: configuration command failed; retaining update",
							serialNumber
						);
						data.configRetryAfterNs = nextRetryTimeNs();
						retainZoneForRetry(serialNumber);
					}
				} catch (RuntimeException e) {
					logger.error(
						"Device {}: configuration delivery failed",
						serialNumber,
						e
					);
					data.configRetryAfterNs = nextRetryTimeNs();
					retainZoneForRetry(serialNumber);
				}
			}
		}
	}

	/** Return whether the given device has pushing device config enabled. */
	private boolean isDeviceConfigEnabled(String serialNumber) {
		DeviceConfig deviceConfig =
			deviceDataManager.getDeviceConfig(serialNumber);
		if (deviceConfig == null) {
			return false;
		}
		return deviceConfig.enableConfig;
	}

	/**
	 * Apply RRM parameters to the device.
	 *
	 * If any changes are needed, modify the config and return true.
	 * Otherwise, return false.
	 */
	boolean applyRRMConfig(
		String serialNumber,
		UCentralApConfiguration config
	) {
		DeviceConfig deviceConfig =
			deviceDataManager.getDeviceConfig(serialNumber);
		if (deviceConfig == null || !deviceConfig.enableRRM) {
			return false;
		}

		boolean modified = false;

		// Apply channel config
		Map<String, Integer> channelList = new HashMap<>();
		if (deviceConfig.autoChannels != null) {
			channelList.putAll(deviceConfig.autoChannels);
		}
		if (deviceConfig.userChannels != null) {
			channelList.putAll(deviceConfig.userChannels);
		}
		if (!channelList.isEmpty()) {
			modified |= UCentralUtils.setRadioConfigField(
				serialNumber,
				config,
				"channel",
				channelList
			);
		}

		// Apply tx power config
		Map<String, Integer> txPowerList = new HashMap<>();
		if (deviceConfig.autoTxPowers != null) {
			txPowerList.putAll(deviceConfig.autoTxPowers);
		}
		if (deviceConfig.userTxPowers != null) {
			txPowerList.putAll(deviceConfig.userTxPowers);
		}
		if (!txPowerList.isEmpty()) {
			modified |= UCentralUtils.setRadioConfigField(
				serialNumber,
				config,
				"tx-power",
				txPowerList
			);
		}

		if (
			deviceConfig.userChannelWidths != null &&
				deviceConfig.userChannelWidths
					.containsKey(UCentralConstants.BAND_2G)
		) {
			modified |= apply2gBandwidth(serialNumber, config, deviceConfig);
		}
		return modified;
	}

	/** Apply bandwidth independently so failure cannot suppress channel or power updates. */
	private boolean apply2gBandwidth(
		String serialNumber,
		UCentralApConfiguration config,
		DeviceConfig settings
	) {
		Integer width =
			settings.userChannelWidths.get(UCentralConstants.BAND_2G);
		DeviceData data =
			deviceDataMap.computeIfAbsent(serialNumber, k -> new DeviceData());
		if (width == null || (width != 20 && width != 40)) {
			data.bandwidthRetryAfterNs = null;
			logger.error(
				"Device {}: invalid persisted bandwidth: {}",
				serialNumber,
				width
			);
			return false;
		}
		if (
			data.bandwidthRetryAfterNs != null && width
				.equals(data.bandwidthRetryWidth) &&
				nanoTime.getAsLong() - data.bandwidthRetryAfterNs < 0
		) {
			retainZoneForRetry(serialNumber);
			return false;
		}
		DeviceCapabilities capabilities;
		try {
			capabilities = client.getCapabilities(serialNumber);
			if (capabilities == null) {
				throw new IllegalStateException(
					"Device capabilities are temporarily unavailable"
				);
			}
		} catch (RuntimeException e) {
			logger.warn(
				"Device {}: cannot retrieve bandwidth capabilities: {}",
				serialNumber,
				e.getMessage()
			);
			data.bandwidthRetryWidth = width;
			data.bandwidthRetryAfterNs = nextRetryTimeNs();
			retainZoneForRetry(serialNumber);
			return false;
		}
		data.bandwidthRetryAfterNs = null;
		try {
			// Validation only reads config. Change the width only after it succeeds.
			validate2gBandwidth(config, settings, capabilities, width);
			return UCentralUtils.setRadioConfigField(
				serialNumber,
				config,
				"channel-width",
				Collections.singletonMap(UCentralConstants.BAND_2G, width)
			);
		} catch (RuntimeException e) {
			// Unsupported/malformed persisted settings do not schedule themselves again.
			// A later config/capability event or periodic evaluation can revalidate them.
			logger.error(
				"Device {}: invalid bandwidth configuration: {}",
				serialNumber,
				e.getMessage()
			);
			return false;
		}
	}

	private long nextRetryTimeNs() {
		return nanoTime.getAsLong() +
			Math.max(1L, params.updateIntervalMs) * 1_000_000L;
	}

	/** Retain work for the existing loop without interrupting its normal sleep. */
	private void retainZoneForRetry(String serialNumber) {
		String zone = deviceDataManager.getDeviceZone(serialNumber);
		if (zone != null) {
			zonesToUpdate.add(zone);
		}
	}

	/** Persist a validated manual selection and enqueue the existing zone delivery pipeline. */
	public synchronized boolean set2gBandwidth(
		DeviceWithStatus device,
		int width
	) {
		String serial = device.serialNumber;
		DeviceConfig settings = deviceDataManager.getDeviceConfig(serial);
		String zone = deviceDataManager.getDeviceZone(serial);
		if (
			!params.configEnabled || settings == null ||
				!Boolean.TRUE.equals(settings.enableConfig) ||
				!Boolean.TRUE.equals(settings.enableRRM) || zone == null
		) {
			throw new IllegalStateException(
				"Configuration updates are disabled or the device has no RRM zone"
			);
		}
		if (!device.connected) {
			throw new IllegalStateException("Device is offline");
		}
		if (device.configuration == null) {
			throw new IllegalArgumentException(
				"Device radio configuration is unavailable"
			);
		}
		UCentralApConfiguration config =
			new UCentralApConfiguration(device.configuration);
		validate2gBandwidth(
			config,
			settings,
			client.getCapabilities(serial),
			width
		);
		boolean changed = UCentralUtils.setRadioConfigField(
			serial,
			config,
			"channel-width",
			Collections.singletonMap(UCentralConstants.BAND_2G, width)
		);
		// AP maps follow the existing whole-field layer precedence. Preserve the
		// effective values of other bands when creating the AP override.
		deviceDataManager.updateDeviceApConfig(configs -> {
			DeviceConfig ap =
				configs.computeIfAbsent(serial, key -> new DeviceConfig());
			Map<String, Integer> widths = new HashMap<>();
			if (ap.userChannelWidths != null) {
				widths.putAll(ap.userChannelWidths);
			} else if (settings.userChannelWidths != null) {
				widths.putAll(settings.userChannelWidths);
			}
			widths.put(UCentralConstants.BAND_2G, width);
			ap.userChannelWidths = widths;
		});
		if (changed) {
			queueZoneAndWakeUp(zone);
		}
		return changed;
	}

	/** Fail closed when radio, width or regulatory channel support cannot be established. */
	static void validate2gBandwidth(
		UCentralApConfiguration config,
		DeviceConfig settings,
		DeviceCapabilities capabilities,
		int width
	) {
		if (width != 20 && width != 40) {
			throw new IllegalArgumentException(
				"Only HT20 and HT40 are supported"
			);
		}
		List<Integer> allowed =
			settings.allowedChannelWidths == null
				? null
				: settings.allowedChannelWidths.get(UCentralConstants.BAND_2G);
		if (allowed != null && !allowed.contains(width)) {
			throw new IllegalArgumentException(
				"Bandwidth is disallowed by allowedChannelWidths"
			);
		}
		JsonObject target = null;
		for (int index = 0; index < config.getRadioCount(); index++) {
			JsonObject radio = config.getRadioConfig(index);
			if (
				radio != null && radio.has("band") &&
					"2G".equals(radio.get("band").getAsString())
			) {
				if (target != null) {
					throw new IllegalArgumentException(
						"Multiple 2.4 GHz radios cannot be targeted unambiguously"
					);
				}
				target = radio;
			}
		}
		if (target == null) {
			throw new IllegalArgumentException("Device has no 2.4 GHz radio");
		}
		Capabilities.Phy phy = null;
		if (
			capabilities != null && capabilities.capabilities != null &&
				capabilities.capabilities.wifi != null
		) {
			for (
				Capabilities.Phy candidate : capabilities.capabilities.wifi
					.values()
			) {
				if (
					candidate != null && candidate.band != null &&
						Arrays.asList(candidate.band).contains("2G")
				) {
					if (phy != null) {
						throw new IllegalArgumentException(
							"Ambiguous 2.4 GHz device capabilities"
						);
					}
					phy = candidate;
				}
			}
		}
		if (
			phy == null || phy.htmode == null || phy.channels == null ||
				Arrays.stream(phy.htmode).noneMatch(mode -> mode != null && mode.matches("(?:HT|VHT|HE|EHT)" + width + "[+-]?"))
		) {
			throw new IllegalArgumentException(
				"Bandwidth is unsupported or device capabilities are unavailable"
			);
		}
		if (
			!target.has("country") || phy.country == null ||
				!phy.country.equalsIgnoreCase(target.get("country").getAsString())
		) {
			throw new IllegalArgumentException(
				"Radio country must match the device regulatory capabilities"
			);
		}
		Set<Integer> channels = new HashSet<>();
		for (int channel : phy.channels) {
			if (channel >= 1 && channel <= 14) {
				channels.add(channel);
			}
		}
		Integer selected = settings.userChannels == null
			? null : settings.userChannels.get("2G");
		if (selected == null && settings.autoChannels != null) {
			selected = settings.autoChannels.get("2G");
		}
		JsonElement configured = target.get("channel");
		if (
			selected == null && configured != null &&
				configured.isJsonPrimitive() &&
				configured.getAsJsonPrimitive().isNumber()
		) {
			selected = configured.getAsInt();
		}
		Set<Integer> primaryChannels = new HashSet<>();
		if (selected != null) {
			primaryChannels.add(selected);
		} else if (
			configured != null && "auto".equals(configured.getAsString())
		) {
			if (target.has("valid-channels")) {
				for (
					JsonElement channel : target
						.getAsJsonArray("valid-channels")
				) {
					primaryChannels.add(channel.getAsInt());
				}
			} else {
				primaryChannels.addAll(channels);
			}
		} else {
			throw new IllegalArgumentException(
				"Cannot determine the configured primary channel"
			);
		}
		if (primaryChannels.isEmpty()) {
			throw new IllegalArgumentException("No supported primary channels");
		}
		for (int channel : primaryChannels) {
			if (
				!channels.contains(channel) || (width == 40 && (channel == 14 ||
					!((channel + 4 <= 13 && channels.contains(channel + 4)) ||
						(channel - 4 >= 1 && channels.contains(channel - 4)))))
			) {
				throw new IllegalArgumentException(
					"Bandwidth is incompatible with the regulatory channel list"
				);
			}
		}
	}

	/**
	 * Add/overwrite a config listener with an arbitrary identifier.
	 *
	 * The "id" string determines the order in which listeners are called.
	 */
	public void addConfigListener(String id, ConfigListener listener) {
		logger.debug("Adding config listener: {}", id);
		configListeners.put(id, listener);
	}

	/**
	 * Remove a config listener with the given identifier, returning true if
	 * anything was actually removed.
	 */
	public boolean removeConfigListener(String id) {
		logger.debug("Removing config listener: {}", id);
		return (configListeners.remove(id) != null);
	}

	/**
	 * Mark the zone to be updated, then interrupt the main thread to possibly
	 * trigger an update immediately.
	 *
	 * @param zone non-null zone (i.e., venue)
	 */
	public void queueZoneAndWakeUp(String zone) {
		if (zone == null) {
			logger.debug("Zone to queue must be a non-null String.");
			return;
		}
		zonesToUpdate.add(zone);
		wakeUp();
	}

	/**
	 * Track all zones to be updated, then interrupt the main thread to possibly
	 * trigger an update immediately.
	 */
	public void queueAllZonesAndWakeUp() {
		/*
		 * Note, addAll is not atomic, but that is ok. This just means that it
		 * is possible that some zones may get updated now by the main thread
		 * while others get updated either when the main thread is woken up or
		 * the next time the main thread does its periodic update.
		 */
		zonesToUpdate.addAll(deviceDataManager.getZones());
		wakeUp();
	}

	/** Interrupt the main thread to possibly trigger an update immediately. */
	private void wakeUp() {
		if (mainThread != null && mainThread.isAlive() && sleepingFlag.get()) {
			wakeupFlag.set(true);
			mainThread.interrupt();
		}
	}
}
